  fun upgradeCostCoins(type: UpgradeType, currentLevel: Int): Int {
    if (currentLevel >= 10) return 0
    val base =
      when (type) {
        UpgradeType.ENGINE -> 220
        UpgradeType.SUSPENSION -> 190
        UpgradeType.TIRES -> 200
        UpgradeType.FUEL_TANK -> 170
        UpgradeType.CHASSIS -> 180
        UpgradeType.TURBO -> 260
        UpgradeType.BRAKES -> 150
        UpgradeType.AIR_CONTROL -> 160
      }
    return (base * (1.42).pow(currentLevel - 1)).roundToInt()
  }

  fun upgradeLevelLabel(type: UpgradeType, level: Int): String {
    return when {
      level <= 1 -> "Lv 1: Stock ${type.title}"
      level <= 4 -> "Lv $level: Tuned ${type.title}"
      level <= 7 -> "Lv $level: Pro Rally"
      level < 10 -> "Lv $level: Championship"
      else -> "Lv 10: MAXED!"
    }
  }
